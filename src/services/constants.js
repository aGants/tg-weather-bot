// Функция валидации порогов
function validateThresholds() {
  // Проверяем, что пороги идут по возрастанию
  const thresholds = Array.from(CLOTHING_ADVICE_MAP.keys()).filter(
    (key) => key !== -Infinity
  );
  const sortedThresholds = [...thresholds].sort((a, b) => b - a);

  if (JSON.stringify(thresholds) !== JSON.stringify(sortedThresholds)) {
    console.warn("⚠️ Пороги температуры не отсортированы по убыванию");
  }

  // Проверяем, что все Maps имеют данные
  if (WEATHER_CODES.size === 0) console.warn("⚠️ WEATHER_CODES пуст");
  if (CLOTHING_ADVICE_MAP.size === 0)
    console.warn("⚠️ CLOTHING_ADVICE_MAP пуст");
  if (UV_LEVELS.size === 0) console.warn("⚠️ UV_LEVELS пуст");
  if (WIND_LEVELS.size === 0) console.warn("⚠️ WIND_LEVELS пуст");
  if (AIR_QUALITY_LEVELS.size === 0) console.warn("⚠️ AIR_QUALITY_LEVELS пуст");

  console.log("✅ Валидация констант завершена");
}

// Запускаем валидацию при импорте (только в development)
if (process.env.NODE_ENV !== "production") {
  validateThresholds();
}

